//! The preview panel: decoded frames, the picture well and the transport bar.
//!
//! Decoding stays in `fig-media` (FFmpeg) on the CPU, exactly where the C# app keeps it; the
//! composited BGRA frame goes to Rune's `NativeSurface` (`push_bytes`, one wgpu texture upload)
//! and is drawn letterboxed in the well. That is the cross-platform frame path proven in
//! `target/research/spikes/rune` — Rune's `Player` itself is macOS-only.
//!
//! Decode demand follows `PreviewViewModel`: a scrub shows the nearest keyframe at once, the exact
//! frame lands when the playhead settles. The two-pass worker lands with playback; snapshots decode
//! synchronously on the UI thread so they are deterministic.

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use fig_fx::Frame;
use fig_media::{DecodeMode, VideoSource};
use fig_timeline::{MediaAsset, Timeline};
use rune::native_surface::{ByteFrame, ColorInfo, Format};
use rune::{El, Pixels, SurfaceFit, el, icon, text};

use crate::app::{AppState, Route};
use crate::editor_state::EditorState;
use crate::icons;
use crate::theme::{font, mono, Tokens, RADIUS_PANEL};

pub const PREVIEW_W: usize = 1920;
pub const PREVIEW_H: usize = 1080;

pub struct PreviewState {
    /// The loader for the sequence being previewed (one open file at a time; the layer compositor
    /// replaces this when `fig-render` is wired for multi-layer frames).
    pub source: Option<VideoSource>,
    /// Rune's latest-wins GPU surface for the frame.
    pub surface: Option<Box<rune::NativeSurface>>,
    /// The frame as pixels too, for the headless fallback and for filmstrip thumbnails.
    pub pixels: Option<Pixels>,
    pub frame_id: u64,
    /// `LastFrameApproximate`: a scrub pass showed the keyframe, not the exact frame.
    pub approximate: bool,
    pub status: String,
    /// Filmstrip thumbnails, one per media source, shared with the timeline's clip drawing.
    pub thumbnails: HashMap<String, Pixels>,
}

impl PreviewState {
    pub fn new() -> PreviewState {
        PreviewState {
            source: None,
            surface: None,
            pixels: None,
            frame_id: 0,
            approximate: false,
            status: String::new(),
            thumbnails: HashMap::new(),
        }
    }

    /// Where the demo media fixtures live (generated by `tools/gen-fixtures.sh`; real projects use
    /// their own absolute media paths once project loading is wired).
    pub fn fixture_dir() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../target/fixtures")
    }

    pub fn fixture_for(source_id: &str) -> Option<PathBuf> {
        let name = match source_id {
            "media-01" | "media-bed" => "media-01.mp4",
            "media-02" => "media-02.mp4",
            "media-03" => "media-03.mp4",
            "media-04" => "media-04.mp4",
            _ => return None,
        };
        let path = Self::fixture_dir().join(name);
        path.exists().then_some(path)
    }

    /// Opens a clip and prepares its surface. False when FFmpeg cannot open it.
    pub fn open(&mut self, path: &Path) -> bool {
        match VideoSource::open(path, PREVIEW_W, PREVIEW_H) {
            Ok(source) => {
                self.source = Some(source);
                self.surface = Some(Box::new(rune::NativeSurface::new()));
                self.status = path.file_name().map_or_else(String::new, |n| n.to_string_lossy().into_owned());
                true
            }
            Err(error) => {
                self.status = error.to_string();
                false
            }
        }
    }

    /// Decodes and presents the frame at `time_sec` (synchronous, for snapshots and still frames).
    pub fn show_at(&mut self, time_sec: f64) {
        let Some(source) = self.source.as_mut() else { return };
        let Some(frame) = source.decode_forward(time_sec.max(0.0), DecodeMode::Playback) else {
            self.status = "No frame".into();
            return;
        };
        self.frame_id += 1;
        let id = self.frame_id;
        if let Some(surface) = self.surface.as_deref() {
            let _ = push_frame(surface, &frame, id);
        }
        self.pixels = Some(to_pixels(&frame, 640, 360));
        self.approximate = source.last_frame_approximate();
        self.status = format!("{}×{}", frame.width, frame.height);
    }

    /// Builds one filmstrip thumbnail per media source in the timeline, from the fixture clips.
    pub fn build_thumbnails(&mut self, doc: &Timeline) {
        let mut wanted: Vec<(String, f64)> = Vec::new();
        for track in &doc.tracks {
            for clip in &track.clips {
                if let Some(id) = clip.media_id() {
                    if !self.thumbnails.contains_key(id) && !wanted.iter().any(|(w, _)| w == id) {
                        wanted.push((id.to_string(), clip.source_in() + clip.dur_sec.min(0.5) * 0.5));
                    }
                }
            }
        }
        for (id, time) in wanted {
            let Some(path) = Self::fixture_for(&id) else { continue };
            let Ok(mut source) = VideoSource::open(&path, 320, 180) else { continue };
            source.seek(time);
            let Some(frame) = source.decode_forward(time, DecodeMode::Scrub) else { continue };
            self.thumbnails.insert(id, to_pixels(&frame, 160, 90));
        }
    }

    /// One thumbnail per project media item (the library grid).
    pub fn build_media_thumbnails(&mut self, media: &[MediaAsset]) {
        for asset in media {
            if self.thumbnails.contains_key(&asset.id) {
                continue;
            }
            let path = std::path::Path::new(&asset.url).to_path_buf();
            let path = if path.exists() { path } else if let Some(p) = Self::fixture_for(&asset.id) { p } else { continue };
            let Ok(mut source) = VideoSource::open(&path, 320, 180) else { continue };
            source.seek(0.5);
            let Some(frame) = source.decode_forward(0.5, DecodeMode::Scrub) else { continue };
            self.thumbnails.insert(asset.id.clone(), to_pixels(&frame, 160, 90));
        }
    }

    pub fn thumbnail(&self, source_id: &str) -> Option<Pixels> {
        self.thumbnails.get(source_id).cloned()
    }

    /// Opens the sequence's first playable clip and shows the frame at `time_sec`, so a project
    /// opens with a picture in the monitor instead of a black well.
    pub fn load_for_doc(&mut self, doc: &Timeline, time_sec: f64) {
        self.load_for_doc_with_media(doc, &[], None, time_sec);
    }

    /// Resolves a media asset's path: absolute as stored, or relative to the project folder.
    fn media_path(media: &[MediaAsset], folder: Option<&Path>, source_id: &str) -> Option<PathBuf> {
        let asset = media.iter().find(|asset| asset.id == source_id)?;
        let path = PathBuf::from(&asset.url);
        let path = if path.is_absolute() { path } else if let Some(folder) = folder { folder.join(path) } else { path };
        path.exists().then_some(path)
    }

    pub fn load_for_doc_with_media(&mut self, doc: &Timeline, media: &[MediaAsset], folder: Option<&Path>, time_sec: f64) {
        let source = doc
            .tracks
            .iter()
            .flat_map(|track| track.clips.iter())
            .find_map(|clip| clip.media_id().map(str::to_string));
        let Some(source) = source else { return };
        let path = Self::media_path(media, folder, &source).or_else(|| Self::fixture_for(&source));
        if let Some(path) = path {
            self.open(&path);
            self.show_at(time_sec);
        }
    }

    /// Filmstrips for a real project: each clip's media path from the project's library.
    pub fn build_thumbnails_for_media(&mut self, doc: &Timeline, media: &[MediaAsset], folder: Option<&Path>) {
        let mut wanted: Vec<(String, f64)> = Vec::new();
        for track in &doc.tracks {
            for clip in &track.clips {
                if let Some(id) = clip.media_id() {
                    if !self.thumbnails.contains_key(id) && !wanted.iter().any(|(w, _)| w == id) {
                        wanted.push((id.to_string(), clip.source_in() + clip.dur_sec.min(0.5) * 0.5));
                    }
                }
            }
        }
        for (id, time) in wanted {
            let path = Self::media_path(media, folder, &id).or_else(|| Self::fixture_for(&id));
            let Some(path) = path else { continue };
            let Ok(mut source) = VideoSource::open(&path, 320, 180) else { continue };
            source.seek(time);
            let Some(frame) = source.decode_forward(time, DecodeMode::Scrub) else { continue };
            self.thumbnails.insert(id, to_pixels(&frame, 160, 90));
        }
    }

    /// The `preview-media` snapshot scene: the first demo clip, one second in.
    pub fn load_demo(&mut self) {
        if let Some(path) = Self::fixture_for("media-01") {
            self.open(&path);
            self.show_at(1.0);
        }
    }
}

/// One upload of an already-composited BGRA frame; the shader samples BGRA directly (no CPU RGBA
/// conversion). The copy into the surface's byte frame is the only per-frame copy here.
fn push_frame(surface: &rune::NativeSurface, frame: &Frame, id: u64) -> Result<(), String> {
    surface.push_bytes(
        ByteFrame {
            width: frame.width as u32,
            height: frame.height as u32,
            format: Format::Bgra,
            color: ColorInfo::default(),
            planes: [frame.pixels.clone(), Vec::new()],
        },
        id,
    )
}

/// Nearest-neighbour downscale to RGBA pixels (filmstrips, headless fallback).
fn to_pixels(frame: &Frame, tw: u32, th: u32) -> Pixels {
    let sw = frame.width.max(1) as u32;
    let sh = frame.height.max(1) as u32;
    let mut rgba = vec![0u8; (tw * th * 4) as usize];
    for y in 0..th {
        let sy = (y * sh / th).min(sh - 1);
        for x in 0..tw {
            let sx = (x * sw / tw).min(sw - 1);
            let si = ((sy * sw + sx) * 4) as usize;
            let di = ((y * tw + x) * 4) as usize;
            rgba[di] = frame.pixels[si + 2];
            rgba[di + 1] = frame.pixels[si + 1];
            rgba[di + 2] = frame.pixels[si];
            rgba[di + 3] = 255;
        }
    }
    let pixels = Pixels::new();
    pixels.set(tw, th, rgba);
    pixels
}

/// The `preview-media` snapshot scene.
pub fn scene_media(state: &mut AppState) {
    state.route = Route::Editor;
    let editor = state.editor();
    editor.playhead = 1.0;
    editor.preview.load_demo();
}

pub fn panel(editor: &EditorState, t: &Tokens) -> El {
    el().grow(1.0)
        .h_full()
        .min_w(360.0)
        .min_h(0.0)
        .fill(t.panel_bg)
        .radius(RADIUS_PANEL)
        .clip_rounded(RADIUS_PANEL)
        .child(
            rune::col()
                .w_full()
                .h_full()
                .padding(12.0)
                .gap(8.0)
                .child(
                    rune::row()
                        .w_full()
                        .h(24.0)
                        .center_y()
                        .child(text("Preview").font(font(14.0, 600.0)).color(t.text_primary)),
                )
                .child(well(editor, t))
                .child(transport(editor, t)),
        )
}

fn well(editor: &EditorState, t: &Tokens) -> El {
    let base = el()
        .w_full()
        .grow(1.0)
        .min_h(0.0)
        .radius(12.0)
        .clip_rounded(12.0)
        .fill(t.preview_well);
    match (&editor.preview.surface, &editor.preview.pixels) {
        (Some(surface), _) => base.child(el().w_full().h_full().native_surface(surface.as_ref(), SurfaceFit::Fit)),
        (None, Some(pixels)) => base.child(el().w_full().h_full().pixels(pixels)),
        (None, None) => base,
    }
}

fn transport(editor: &EditorState, t: &Tokens) -> El {
    let playing = editor.transport.playing;
    let controls = rune::row()
        .gap(14.0)
        .center_y()
        .child(icon(&icons::SKIP_BACK, 14.0).color(t.text_muted).on_press(|s: &mut AppState| {
            let e = s.editor();
            e.playhead = 0.0;
            e.transport.clock_sec = 0.0;
        }))
        .child(
            icon(&icons::SKIP_BACK, 14.0)
                .color(t.text_muted)
                .on_press(|s: &mut AppState| step_frames(s, -1)),
        )
        .child(
            icon(if playing { &icons::PAUSE } else { &icons::PLAY }, 14.0)
                .color(t.text_secondary)
                .on_press(|s: &mut AppState| s.editor().transport.toggle_play()),
        )
        .child(
            icon(&icons::SKIP_FORWARD, 14.0)
                .color(t.text_muted)
                .on_press(|s: &mut AppState| step_frames(s, 1)),
        )
        .child(icon(&icons::SKIP_FORWARD, 14.0).color(t.text_muted).on_press(|s: &mut AppState| {
            let e = s.editor();
            e.playhead = e.duration_sec();
        }))
        .child(icon(&icons::REDO, 14.0).color(t.text_muted));

    let right = rune::row()
        .gap(10.0)
        .center_y()
        .child(icon(&icons::VOLUME, 14.0).color(t.text_muted))
        .child(el().w(70.0).h(3.0).radius(2.0).fill(t.accent))
        .child(crate::widgets::chip("360p", t))
        .child(icon(&icons::PANEL_RIGHT, 14.0).color(t.text_faint));

    // narrow preview panels (a small inspector + a wide library, as the user's workspace.json has)
    // must not let the timecode run over the transport controls
    rune::row()
        .w_full()
        .h(26.0)
        .center_y()
        .child(
            el().grow(1.0).min_w(0.0).center_y().child(
                text(format!("{} / {}", editor.playhead_timecode(), editor.timecode(editor.duration_sec())))
                    .font(mono(11.0, 400.0))
                    .color(t.text_secondary)
                    .truncate(),
            ),
        )
        .child(controls)
        .child(el().grow(1.0).max_w(12.0))
        .child(right)
}

fn step_frames(app: &mut AppState, delta: i64) {
    let rate = app.editor().project_rate().max(1.0);
    let step = delta as f64 / rate;
    let e = app.editor();
    let duration = e.duration_sec();
    e.playhead = (e.playhead + step).clamp(0.0, duration);
    e.transport.clock_sec = e.playhead;
}
